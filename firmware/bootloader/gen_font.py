#!/usr/bin/env python3
"""Generates boot_font.h: only the glyphs that the bootloader's messages use.

Reads the PROGMEM strings of boot.c (plus the countdown digits) and takes the
glyph bitmaps from the U8x8 font file (8 column bytes per glyph, LSB on top).
"""
import re
import sys

source, font_file, out = sys.argv[1:4]
text = open(source).read()
chars = set()
for message in re.findall(r'PROGMEM\s*=\s*"([^"]*)"', text):
    chars.update(message)
chars.discard(" ")
chars.discard("\\")  # from \0 escapes in string literals
charset = " " + "".join(sorted(chars))
font = open(font_file, "rb").read()
first = font[0]
lines = ['// Generated by gen_font.py, do not edit.',
         '#include <avr/pgmspace.h>',
         f'static const char CHARSET[] PROGMEM = "{charset}";',
         'static const uint8_t GLYPHS[] PROGMEM = {']
for c in charset:
    offset = 4 + (ord(c) - first) * 8
    glyph = b"\xff" * 8 if c == "^" else font[offset:offset + 8]  # '^' is a solid block
    lines.append("    " + ", ".join(f"0x{b:02X}" for b in glyph) + f",  // '{c}'")
lines.append("};")
lines.append(f"#define CHARSET_SIZE {len(charset)}")
open(out, "w").write("\n".join(lines) + "\n")
print(f"{len(charset)} glyphs: {charset!r}")
